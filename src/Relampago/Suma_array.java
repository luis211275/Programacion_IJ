package Relampago;

public class Suma_array {
    public static void main(String[] args) {
        int[] numeros = {2, 3};
        int suma = 0;
        for (int i = 0; i < numeros.length; i++) {
            suma += numeros[i];
        }
        System.out.println("La suma del array es: " + suma);
    }
}


